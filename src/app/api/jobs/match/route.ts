import { NextRequest, NextResponse } from "next/server";
import { DEMO_USER_SKILLS } from "@/lib/mock-data";

// ─── Types ───────────────────────────────────────────────────────────────────

export interface MatchInput {
  jobId: string;
  jobTitle: string;
  jobDescription: string;
  jobTags: string[];
  /** Optional: employment type from the job listing */
  jobType?: string;
}

/**
 * Breakdown of how each scoring dimension contributed.
 * All values are 0–100, representing alignment within that dimension only.
 */
export interface MatchDimensions {
  /** How many required/preferred skills the student has vs the job needs */
  skillAlignment: number;
  /** How well the job title/category matches the student's target role */
  roleAlignment: number;
  /** Whether the job's experience level is appropriate for the student */
  levelFit: number;
  /** How well the student's stated preferences (location/type) match the job */
  preferenceFit: number;
}

/**
 * Extended match result returned for each job.
 * Extends the original interface — all existing fields are preserved.
 */
export interface EnrichedMatchResult {
  // ── Original fields (backward-compatible) ──────────────────────────────────
  jobId: string;
  /** 0–100 overall profile-to-job alignment score (NOT a hiring probability). */
  matchScore: number;
  matchedSkills: string[];
  missingSkills: string[];
  /** One-line summary, max 150 chars */
  matchReason: string;
  fitLabel: "Strong Fit" | "Good Fit" | "Partial Fit" | "Low Fit";

  // ── New enriched fields ────────────────────────────────────────────────────
  /** Per-dimension sub-scores so students can see where they stand */
  dimensions: MatchDimensions;
  /**
   * Specific, actionable next steps grounded in actual job requirements.
   * Each item cites the gap it addresses.
   */
  improvements: string[];
  /**
   * Skills the student lists that directly align with this job.
   * A subset of matchedSkills filtered to the most prominent.
   */
  strengths: string[];
  /**
   * Requirements mentioned in the job description that cannot be verified
   * from the student's profile (neither confirmed nor denied).
   */
  unknownRequirements: string[];
  /**
   * Indicates the source of the explanation:
   *  "gemini"    – explanation generated by Gemini 2.0 Flash, validated against schema
   *  "heuristic" – explanation produced by the deterministic fallback algorithm
   */
  scoreSource: "gemini" | "heuristic";
}

// ─── Skill synonym map ────────────────────────────────────────────────────────
// Maps an alias to its canonical skill name. Both directions are checked.
// This prevents penalising students for using one valid term over another.

const SKILL_SYNONYMS: Record<string, string[]> = {
  "React":        ["ReactJS", "React.js", "react"],
  "Node.js":      ["NodeJS", "Node", "node.js"],
  "TypeScript":   ["TS", "Typescript"],
  "JavaScript":   ["JS", "ES6", "ES2015", "Vanilla JS"],
  "PostgreSQL":   ["Postgres", "pg", "PSQL"],
  "MongoDB":      ["Mongo", "mongoose"],
  "Python":       ["py", "python3"],
  "Docker":       ["containerisation", "containerization"],
  "Kubernetes":   ["k8s", "kube"],
  "REST APIs":    ["RESTful", "REST", "REST API"],
  "GraphQL":      ["gql"],
  "CI/CD":        ["continuous integration", "continuous deployment", "github actions", "pipeline"],
  "System Design":["distributed systems", "architecture design"],
  "Machine Learning": ["ML", "deep learning", "AI/ML"],
  "Git":          ["version control", "github", "gitlab"],
  "AWS":          ["Amazon Web Services", "cloud (aws)"],
  "GCP":          ["Google Cloud", "Google Cloud Platform"],
  "Azure":        ["Microsoft Azure", "cloud (azure)"],
};

/**
 * Resolves a skill name to its canonical form, accounting for synonyms.
 * Returns the skill unchanged if no synonym match is found.
 */
function canonicalise(skill: string): string {
  const lower = skill.toLowerCase().trim();
  for (const [canonical, aliases] of Object.entries(SKILL_SYNONYMS)) {
    const allForms = [canonical, ...aliases].map((s) => s.toLowerCase());
    if (allForms.includes(lower)) return canonical;
  }
  return skill;
}

/**
 * Returns true if `needle` can be found in `haystack` after canonicalisation.
 */
function skillMatchExists(needle: string, haystack: string[]): boolean {
  const canonNeedle = canonicalise(needle).toLowerCase();
  return haystack.some((h) => canonicalise(h).toLowerCase() === canonNeedle);
}

// ─── Tech keyword extraction ──────────────────────────────────────────────────

const ALL_TECH_KEYWORDS = [
  "React", "Angular", "Vue", "TypeScript", "JavaScript", "Python", "Java",
  "Go", "Rust", "C++", "Node.js", "Next.js", "GraphQL", "REST APIs",
  "SQL", "PostgreSQL", "MongoDB", "Redis", "Docker", "Kubernetes",
  "AWS", "GCP", "Azure", "Machine Learning", "DevOps", "CI/CD",
  "Spring Boot", "Django", "Swift", "Kotlin", "Terraform", "Kafka",
  "System Design", "Microservices", "Git", "Linux", "React Native",
  "PyTorch", "TensorFlow", "NLP", "LLMs", "WebGL", "WebSocket",
];

/**
 * Extracts tech keywords that appear in a JD / tags string.
 */
function extractJobKeywords(text: string): string[] {
  const lower = text.toLowerCase();
  const found = new Set<string>();
  for (const kw of ALL_TECH_KEYWORDS) {
    if (lower.includes(kw.toLowerCase())) found.add(kw);
  }
  return Array.from(found);
}

// ─── Role alignment helpers ───────────────────────────────────────────────────

const ROLE_CATEGORY_MAP: Record<string, string[]> = {
  frontend:  ["frontend", "front-end", "front end", "react developer", "ui engineer", "css", "html", "web developer"],
  backend:   ["backend", "back-end", "back end", "server-side", "api engineer", "database engineer"],
  fullstack: ["full stack", "fullstack", "full-stack", "product engineer", "software engineer", "swe", "sde"],
  devops:    ["devops", "sre", "platform engineer", "infrastructure", "cloud engineer", "devsecops"],
  mobile:    ["ios developer", "android developer", "mobile engineer", "react native", "flutter"],
  ml:        ["machine learning", "ml engineer", "data scientist", "ai engineer", "nlp engineer"],
  data:      ["data analyst", "data engineer", "analytics", "business intelligence"],
};

function inferJobCategory(title: string, description: string): string {
  const text = `${title} ${description}`.toLowerCase();
  for (const [category, keywords] of Object.entries(ROLE_CATEGORY_MAP)) {
    if (keywords.some((kw) => text.includes(kw))) return category;
  }
  return "general";
}

function inferTargetCategory(targetRole: string): string {
  const lower = targetRole.toLowerCase();
  for (const [category, keywords] of Object.entries(ROLE_CATEGORY_MAP)) {
    if (keywords.some((kw) => lower.includes(kw))) return category;
  }
  return "general";
}

// ─── Experience level helpers ─────────────────────────────────────────────────

const SENIOR_SIGNALS = ["senior", "sr.", "lead", "principal", "staff", "sde-3", "sde3", "l5", "l6"];
const MID_SIGNALS    = ["sde-2", "sde2", "mid", "intermediate", "level 2", "l4", "2+ years", "3+ years", "4+ years"];
const JUNIOR_SIGNALS = ["junior", "jr.", "entry", "sde-1", "sde1", "l3", "0-2 years", "0-1 year", "fresher", "graduate"];
const INTERN_SIGNALS = ["intern", "internship", "trainee", "apprentice"];

type ExperienceLevel = "intern" | "fresher" | "junior" | "mid" | "senior" | "unknown";

function inferExperienceLevel(title: string, description: string): ExperienceLevel {
  const text = `${title} ${description}`.toLowerCase();
  if (INTERN_SIGNALS.some((s) => text.includes(s))) return "intern";
  if (JUNIOR_SIGNALS.some((s) => text.includes(s))) return "fresher";
  if (SENIOR_SIGNALS.some((s) => text.includes(s))) return "senior";
  if (MID_SIGNALS.some((s) => text.includes(s))) return "mid";
  // If no clear signal and the job type is internship, default to intern
  return "unknown";
}

/**
 * Returns a 0–100 score for how well a student's level fits the job's level.
 * Entry-level candidates are NOT penalised for jobs explicitly labelled for
 * fresh graduates or interns.
 */
function computeLevelFit(
  jobLevel: ExperienceLevel,
  isStudent: boolean,
  jobType?: string
): number {
  const isInternship = jobType?.toLowerCase().includes("intern") ?? false;

  if (isStudent || isInternship) {
    // Students/freshers are appropriate for intern and fresher roles
    if (jobLevel === "intern" || jobLevel === "fresher" || jobLevel === "unknown") return 95;
    if (jobLevel === "junior") return 75;
    if (jobLevel === "mid") return 45;
    if (jobLevel === "senior") return 20;
  }

  // Generic: unknown level gets neutral score
  if (jobLevel === "unknown") return 70;
  return 70; // Default neutral when we can't assess the student level
}

// ─── Preference fit helper ────────────────────────────────────────────────────

function computePreferenceFit(
  jobLocation: string,
  jobType: string,
  preferredLocation: string,
  preferredTypes: string[]
): number {
  let score = 70; // neutral baseline

  // Location preference
  if (preferredLocation) {
    const pref = preferredLocation.toLowerCase();
    const loc  = jobLocation.toLowerCase();
    if (pref === "remote" && (loc.includes("remote") || loc.includes("work from home"))) {
      score += 20;
    } else if (pref !== "remote" && loc.includes(pref)) {
      score += 20;
    } else if (pref !== "remote" && loc.includes("remote")) {
      score += 5; // Remote is often acceptable even if not preferred
    } else if (preferredLocation) {
      score -= 15; // Location mismatch penalty
    }
  }

  // Job type preference
  if (preferredTypes.length > 0) {
    if (preferredTypes.some((t) => t.toLowerCase() === jobType.toLowerCase())) {
      score += 10;
    }
  }

  return Math.min(100, Math.max(0, score));
}

// ─── Heuristic scoring (deterministic fallback) ───────────────────────────────

function scoreHeuristic(
  job: MatchInput,
  userSkills: string[],
  userTargetRole: string,
  preferredLocation: string,
  preferredTypes: string[]
): EnrichedMatchResult {
  const jdText = `${job.jobTitle} ${job.jobDescription} ${job.jobTags.join(" ")}`;
  const jobKeywords = extractJobKeywords(jdText);

  // ── Skill alignment ──────────────────────────────────────────────────────
  const matchedSkills: string[]    = [];
  const missingSkills: string[]    = [];
  const unknownRequirements: string[] = [];

  for (const skill of userSkills) {
    if (skillMatchExists(skill, jobKeywords) || skillMatchExists(skill, job.jobTags)) {
      matchedSkills.push(skill);
    }
  }

  for (const kw of jobKeywords) {
    if (!skillMatchExists(kw, userSkills)) {
      missingSkills.push(kw);
    }
  }

  const totalRelevant = matchedSkills.length + missingSkills.length;
  const skillScore =
    totalRelevant === 0
      ? 50 // neutral — can't assess
      : Math.round((matchedSkills.length / totalRelevant) * 100);

  // Unknown: requirements that appear in description but aren't in keyword list
  const descLower = job.jobDescription.toLowerCase();
  const vagueTerms = ["experience with", "knowledge of", "familiarity with", "understanding of"];
  for (const term of vagueTerms) {
    if (descLower.includes(term)) {
      unknownRequirements.push("Some requirements could not be verified from available profile data");
      break;
    }
  }

  // ── Role alignment ───────────────────────────────────────────────────────
  const jobCategory    = inferJobCategory(job.jobTitle, job.jobDescription);
  const targetCategory = inferTargetCategory(userTargetRole);
  const roleScore      = jobCategory === targetCategory ? 90
    : jobCategory === "general" || targetCategory === "general" ? 60
    : 35;

  // ── Level fit ────────────────────────────────────────────────────────────
  const jobLevel  = inferExperienceLevel(job.jobTitle, job.jobDescription);
  const levelScore = computeLevelFit(jobLevel, true, job.jobType);

  // ── Preference fit ───────────────────────────────────────────────────────
  const prefScore = computePreferenceFit(
    job.jobDescription,   // location often mentioned in description for external jobs
    job.jobType ?? "Full-time",
    preferredLocation,
    preferredTypes
  );

  // ── Weighted composite score ──────────────────────────────────────────────
  // Weights reflect which dimensions are most actionable for campus placement:
  //   Skill alignment:  45% — most directly relevant and verifiable
  //   Role alignment:   25% — important for career direction
  //   Level fit:        20% — key for campus/fresher context
  //   Preference fit:   10% — personalization signal
  const composite = Math.round(
    skillScore * 0.45 +
    roleScore  * 0.25 +
    levelScore * 0.20 +
    prefScore  * 0.10
  );

  // Clamp
  const matchScore = Math.min(100, Math.max(10, composite));

  const fitLabel: EnrichedMatchResult["fitLabel"] =
    matchScore >= 85 ? "Strong Fit" :
    matchScore >= 70 ? "Good Fit"   :
    matchScore >= 50 ? "Partial Fit":
    "Low Fit";

  // ── Match reason ─────────────────────────────────────────────────────────
  const matchReason =
    matchedSkills.length > 0
      ? `${matchedSkills.length} matched skill${matchedSkills.length > 1 ? "s" : ""}: ${matchedSkills.slice(0, 3).join(", ")}.${missingSkills.length > 0 ? ` Gap: ${missingSkills.slice(0, 2).join(", ")}.` : " Strong alignment."}`
      : "Limited skill overlap detected. Consider this a stretch role to grow your profile.";

  // ── Improvement suggestions ───────────────────────────────────────────────
  const improvements: string[] = [];

  if (missingSkills.length > 0) {
    const topMissing = missingSkills.slice(0, 3);
    improvements.push(`Build hands-on experience with ${topMissing.join(", ")} — they appear in the job requirements.`);
  }
  if (roleScore < 60) {
    improvements.push(`Your target role (${userTargetRole}) may differ from this position (${job.jobTitle}). Review if this role aligns with your career direction.`);
  }
  if (levelScore < 60) {
    improvements.push("This role may require more experience than typically expected for fresh graduates. Consider it a long-term target.");
  }
  if (skillScore < 50 && matchedSkills.length < 2) {
    improvements.push("Add relevant projects or coursework to demonstrate your skills in the missing areas.");
  }

  // ── Top strengths ─────────────────────────────────────────────────────────
  const strengths = matchedSkills.slice(0, 4);

  return {
    jobId:                job.jobId,
    matchScore,
    matchedSkills,
    missingSkills:        missingSkills.slice(0, 5),
    matchReason:          matchReason.slice(0, 150),
    fitLabel,
    dimensions: {
      skillAlignment: skillScore,
      roleAlignment:  roleScore,
      levelFit:       levelScore,
      preferenceFit:  prefScore,
    },
    improvements,
    strengths,
    unknownRequirements,
    scoreSource: "heuristic",
  };
}

// ─── Gemini scoring ───────────────────────────────────────────────────────────

async function scoreWithGemini(
  job: MatchInput,
  userSkills: string[],
  userTargetRole: string,
  preferredLocation: string,
  preferredTypes: string[]
): Promise<EnrichedMatchResult | null> {
  const apiKey = process.env.GOOGLE_GENERATIVE_AI_API_KEY;
  if (!apiKey) return null;

  try {
    const prefContext =
      preferredLocation || preferredTypes.length > 0
        ? `\n- Preferred location: ${preferredLocation || "Not specified"}\n- Preferred job types: ${preferredTypes.length > 0 ? preferredTypes.join(", ") : "Not specified"}`
        : "";

    const prompt = `You are a job-match scoring engine for a campus placement platform. Provide a transparent, evidence-based assessment — NOT a hiring probability.

Student Profile:
- Demonstrated skills: ${userSkills.join(", ")}
- Target role: ${userTargetRole}${prefContext}

Job Details:
- Title: ${job.jobTitle}
- Type: ${job.jobType ?? "Full-time"}
- Description (first 600 chars): ${job.jobDescription.slice(0, 600)}
- Required/preferred tags: ${job.jobTags.join(", ")}

Scoring rules you MUST follow:
1. matchScore (0–100) is a profile-to-job ALIGNMENT score, NOT a hiring probability.
2. Only list skills in matchedSkills if they appear in BOTH the student's demonstrated skills AND the job requirements.
3. Only list skills in missingSkills if they are explicitly required or strongly preferred in the job description/tags. Max 5.
4. unknownRequirements: requirements in the JD that cannot be verified from the student profile. Be specific.
5. improvements: 1–3 actionable, job-specific next steps tied to actual gaps. Do NOT suggest fabricating skills.
6. strengths: up to 4 student skills that directly appear in or relate to this job.
7. dimensions: compute subscores (0–100) for skillAlignment, roleAlignment, levelFit, preferenceFit.
8. levelFit should NOT penalize a student for being a fresher if the job is an internship or entry-level role.

Respond ONLY with valid JSON (no markdown, no backticks):
{
  "matchScore": <number 0-100>,
  "matchedSkills": [<skills from student list that appear in the JD>],
  "missingSkills": [<skills required by job that student lacks, max 5>],
  "matchReason": "<one-line summary grounded in evidence, max 150 chars>",
  "fitLabel": "<one of: Strong Fit, Good Fit, Partial Fit, Low Fit>",
  "dimensions": {
    "skillAlignment": <0-100>,
    "roleAlignment": <0-100>,
    "levelFit": <0-100>,
    "preferenceFit": <0-100>
  },
  "improvements": [<1-3 specific, actionable strings>],
  "strengths": [<up to 4 student skills that match the job>],
  "unknownRequirements": [<requirements that can't be verified from profile>]
}`;

    const res = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key=${apiKey}`,
      {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          contents: [{ parts: [{ text: prompt }] }],
          generationConfig: {
            temperature: 0.1, // Lower temperature for more deterministic, evidence-based output
            maxOutputTokens: 500,
          },
        }),
        signal: AbortSignal.timeout(10000),
      }
    );

    if (!res.ok) return null;

    const data = await res.json();
    const text: string = data?.candidates?.[0]?.content?.parts?.[0]?.text || "";

    const jsonMatch = text.match(/\{[\s\S]*\}/);
    if (!jsonMatch) return null;

    const parsed = JSON.parse(jsonMatch[0]);

    // ── Schema validation — reject malformed AI outputs ───────────────────
    if (
      typeof parsed.matchScore !== "number" ||
      !Array.isArray(parsed.matchedSkills) ||
      !Array.isArray(parsed.missingSkills) ||
      typeof parsed.matchReason !== "string" ||
      !["Strong Fit", "Good Fit", "Partial Fit", "Low Fit"].includes(parsed.fitLabel) ||
      typeof parsed.dimensions !== "object" ||
      typeof parsed.dimensions.skillAlignment !== "number"
    ) {
      // AI response did not conform to expected schema — fall back to heuristic
      return null;
    }

    // Clamp all numeric fields to valid range
    const clamp = (n: number) => Math.min(100, Math.max(0, Math.round(n)));

    return {
      jobId:                job.jobId,
      matchScore:           clamp(parsed.matchScore ?? 50),
      matchedSkills:        (parsed.matchedSkills || []).slice(0, 10),
      missingSkills:        (parsed.missingSkills || []).slice(0, 5),
      matchReason:          (parsed.matchReason || "").slice(0, 150),
      fitLabel:             parsed.fitLabel,
      dimensions: {
        skillAlignment: clamp(parsed.dimensions?.skillAlignment ?? 50),
        roleAlignment:  clamp(parsed.dimensions?.roleAlignment ?? 50),
        levelFit:       clamp(parsed.dimensions?.levelFit ?? 70),
        preferenceFit:  clamp(parsed.dimensions?.preferenceFit ?? 70),
      },
      improvements:         (Array.isArray(parsed.improvements) ? parsed.improvements : []).slice(0, 3),
      strengths:            (Array.isArray(parsed.strengths) ? parsed.strengths : []).slice(0, 4),
      unknownRequirements:  (Array.isArray(parsed.unknownRequirements) ? parsed.unknownRequirements : []).slice(0, 3),
      scoreSource:          "gemini",
    };
  } catch {
    return null;
  }
}

// ─── In-memory cache (resets on redeploy) ────────────────────────────────────

const matchCache = new Map<string, EnrichedMatchResult>();

// ─── Route Handler ───────────────────────────────────────────────────────────

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();

    // Input validation
    if (!body || typeof body !== "object") {
      return NextResponse.json({ error: "Invalid request body." }, { status: 400 });
    }

    const jobs: MatchInput[]     = Array.isArray(body.jobs) ? body.jobs : [];
    const userSkills: string[]   = Array.isArray(body.userSkills) ? body.userSkills : DEMO_USER_SKILLS;
    const userTargetRole: string = typeof body.userTargetRole === "string" ? body.userTargetRole : "Software Engineer";
    const preferredLocation: string = typeof body.preferredLocation === "string" ? body.preferredLocation : "";
    const preferredTypes: string[]  = Array.isArray(body.preferredTypes) ? body.preferredTypes : [];

    if (jobs.length === 0) {
      return NextResponse.json({ results: [], cached: 0, scored: 0 });
    }

    // Build a cache key that includes preference context so different user
    // preferences get different cached results even for the same job ID.
    const prefKey = `${preferredLocation}|${preferredTypes.sort().join(",")}`;
    const getCacheKey = (jobId: string) => `${jobId}::${prefKey}`;

    const uncachedJobs: MatchInput[]    = [];
    const cachedResults: EnrichedMatchResult[] = [];

    for (const job of jobs) {
      const cached = matchCache.get(getCacheKey(job.jobId));
      if (cached) {
        cachedResults.push(cached);
      } else {
        uncachedJobs.push(job);
      }
    }

    const scoringPromises = uncachedJobs.map(async (job) => {
      // Try Gemini first; fall back to heuristic if unavailable or output is invalid
      const geminiResult = await scoreWithGemini(
        job, userSkills, userTargetRole, preferredLocation, preferredTypes
      );
      const result = geminiResult ?? scoreHeuristic(
        job, userSkills, userTargetRole, preferredLocation, preferredTypes
      );

      matchCache.set(getCacheKey(job.jobId), result);
      return result;
    });

    const newResults = await Promise.allSettled(scoringPromises);

    const allResults: EnrichedMatchResult[] = [
      ...cachedResults,
      ...newResults
        .filter((r): r is PromiseFulfilledResult<EnrichedMatchResult> => r.status === "fulfilled")
        .map((r) => r.value),
    ];

    return NextResponse.json({
      results: allResults,
      cached:  cachedResults.length,
      scored:  newResults.filter((r) => r.status === "fulfilled").length,
    });
  } catch (err) {
    return NextResponse.json(
      { error: err instanceof Error ? err.message : "Match scoring failed" },
      { status: 500 }
    );
  }
}
